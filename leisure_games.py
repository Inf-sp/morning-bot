def _link(name, kind) -> str:
    """Где посмотреть: настольная — BoardGameGeek, PS5 — трейлер на YouTube."""
    if kind == "board":
        return f"https://boardgamegeek.com/geeksearch.php?action=search&objecttype=boardgame&q={quote_plus(name)}"
    return f"https://www.youtube.com/results?search_query={quote_plus(name + ' PS5 trailer')}"


def game_of_day(day) -> dict:
    """Игра на этот день: чётные дни — настольная, нечётные — PS5; внутри вида — по кругу по датам."""
    number = day.toordinal()
    kind, pool = ("board", BOARD) if number % 2 == 0 else ("ps5", PS5)
    name, meta, about = pool[(number // 2) % len(pool)]
    return {"kind": "game", "name": name, "url": _link(name, kind),
            "meta": ["настольная" if kind == "board" else "PS5", meta], "about": about}
