def _fridge_normalize_input(text: str) -> str:
    """Подготовить пользовательский список: HTML/маркированный текст -> строки продуктов."""
    t = html.unescape(str(text or ""))
    t = re.sub(r"(?i)<\s*br\s*/?\s*>", "\n", t)
    t = re.sub(r"(?i)<\s*/\s*li\s*>", "\n", t)
    t = re.sub(r"(?i)<\s*li[^>]*>", "\n", t)
    t = re.sub(r"(?i)<\s*/?\s*(ul|ol)[^>]*>", "\n", t)
    t = re.sub(r"<[^>]+>", "", t)
    return t


_FROZEN_RE = re.compile(r"\b(?:заморож\w*|замороз\w*|мороже?н(?:ые|ая|ый|ое)?|frozen|diepvries)\b", re.I)


def _fridge_detect_cat(name: str) -> str | None:
    """Определить одну из девяти категорий или вернуть None при низкой уверенности. Категория — по типу продукта:
    «замороженные овощи» — овощи, «замороженная рыба» — рыба; замороженное без типа — полуфабрикаты."""
    n = str(name or "").lower()
    if n in _FRIDGE_CAT_EXACT:
        return _FRIDGE_CAT_EXACT[n]
    if _FROZEN_RE.search(n) and "мороженое" not in n:
        rest = _FROZEN_RE.sub(" ", n).strip()
        return (_fridge_detect_cat(rest) if rest else None) or "колбасы и полуфабрикаты"
    if any(phrase in n for phrase in ("томатная паст", "паста том", "том ям", "том-ям", "том кха", "tom yam", "tom kha")):
        return "соусы и специи"
    if n in ("ui", "uien", "sla", "kropsla"):
        return "овощи и зелень"
    if n == "ham":
        return "колбасы и полуфабрикаты"
    if n in ("water", "mineraalwater"):
        return "сладкое и напитки"
    if n == "watermeloen":
        return "фрукты и ягоды"
    if n in ("paprika", "rode paprika", "gele paprika", "groene paprika"):
        return "овощи и зелень"
    if "перец" in n:
        if any(k in n for k in ("чёрн", "черн", "молот", "душист", "чили", "cayenne", "кайен")):
            return "соусы и специи"
        return "овощи и зелень"
    if "koolsla" in n or "coleslaw" in n or "cole slaw" in n or "коул слоу" in n or "кол слоу" in n:
        return "овощи и зелень"
    for cat, keywords in _FRIDGE_KEYWORDS.items():
        if any(k in n for k in keywords):
            return cat
    return None


def _fridge_cat(name: str) -> str:
    """Совместимый детерминированный fallback без категории «Прочее».

    Интерактивное добавление использует _fridge_detect_cat() и при None просит
    пользователя выбрать категорию. Fallback нужен для старых записей и
    неинтерактивных сценариев миграции.
    """
    return _fridge_detect_cat(name) or "крупы, макароны и хлеб"


def _fridge_clean_name(name: str) -> str:
    """Приводит продукт к одному читаемому названию без смены смысла."""
    n = _fridge_normalize_input(name)
    n = re.sub(r"\s+", " ", str(n).lower().strip(" -—:•\t"))
    n = re.sub(r"^[^\wа-яё]+", "", n, flags=re.IGNORECASE).strip()
    for pattern in _FRIDGE_BRAND_PATTERNS:
        n = re.sub(pattern, "", n).strip()
    n = re.sub(r"\([^)]*\)", "", n).strip()
    if n in _FRIDGE_NAME_EXACT:
        return _FRIDGE_NAME_EXACT[n]
    if n.startswith("свежий ") or n.startswith("свежая "):
        n = re.sub(r"^свеж(ий|ая|ее|ие)\s+", "", n).strip()
    if "koolsla" in n or "coleslaw" in n or "cole slaw" in n or "коул слоу" in n or "кол слоу" in n:
        return "коул слоу"
    if "греч" in n:
        return "гречка"
    if "карто" in n and "фри" in n:
        return "картофель фри"
    if "кур" in n and "нож" in n:
        return "куриные ножки"
    if "коп" in n and "кур" in n:
        return "копчёная курица"
    if "сельд" in n or "селед" in n or "селёд" in n:
        return "сельдь"
    if "лосос" in n:
        return "лосось"
    if "кревет" in n:
        return "креветки"
    if "краб" in n and "палоч" in n:
        return "крабовые палочки"
    if "котлет" in n:
        return "котлета"
    if "пицц" in n:
        return "пицца"
    if "тток" in n or "topokki" in n or "tteok" in n or "yopokki" in n:
        return "ттокпокки"
    if "томат" in n and "паст" in n:
        return "томатная паста"
    if "фасол" in n:
        return "фасоль"
    if "кукуруз" in n:
        return "кукуруза"
    if "том" in n and ("ям" in n or "кха" in n):
        return "том ям"
    if "бульон" in n:
        return "бульон"
    if "масло" in n and "подсолн" in n:
        return "подсолнечное масло"
    if "масло" in n and ("слив" in n or "мягк" in n):
        return "сливочное масло"
    words = n.split()
    if len(words) > 2:
        n = " ".join(words[:2])
    return n


def _fridge_split_input(text: str) -> list[str]:
    """Разбивает пользовательский список на отдельные продукты."""
    out: list[str] = []
    for raw_line in _fridge_normalize_input(text).splitlines():
        line = raw_line.strip()
        if not line:
            continue
        low = line.lower().strip(" -—:•\t")
        if not _fridge_is_product(low):
            continue
        if low in _FRIDGE_LINE_SPLITS:
            out.extend(_FRIDGE_LINE_SPLITS[low])
            continue
        inner = re.findall(r"\(([^)]*)\)", low)
        line_no_parens = re.sub(r"\([^)]*\)", "", low).strip(" :")
        # Старые импортированные списки встречались как «Фрукты: (киви, …)».
        # Заголовок такой группы не является продуктом; содержимое скобок
        # разбирается как обычный список. Простая «курица» при этом остаётся
        # одним продуктом и больше не разворачивается в выдуманный набор частей.
        chunks = [] if inner and line_no_parens in _FRIDGE_SPLIT_PREFIXES else [line_no_parens]
        chunks.extend(inner)
        for chunk in chunks:
            chunk = re.sub(r"\s+-\s+.*$", "", chunk).strip()
            parts = re.split(r",|;|/|\s+или\s+|\s+и\s+", chunk)
            for part in parts:
                name = _fridge_clean_name(part)
                if _fridge_is_product(name):
                    out.append(name)
    result = []
    seen = set()
    for name in out:
        key = name.casefold()
        if key not in seen:
            seen.add(key)
            result.append(name)
    return result


def _fridge_reject_reason(line: str) -> str:
    """Коротко объясняет, почему строка из большого списка не стала продуктом."""
    low = str(line).lower().strip(" -—:•\t")
    if not low:
        return ""
    if any(p in low for p in ("fresh market", "oost-europese supermarkt")):
        return "это название магазина/раздела"
    if "бумажные полотенца" in low:
        return "это не продукт"
    if "редкие покупки" in low or "редкие продукты" in low:
        return "это заголовок, а не продукт"
    if any(p in low for p in ("список", "категория", "прочее", "другое")):
        return "это служебная строка"
    if low in _FRIDGE_NOT_PRODUCT_EXACT:
        return "это уточнение без продукта"
    return ""


def _fridge_rejected_lines(text: str) -> list[tuple[str, str]]:
    rejected = []
    for raw_line in _fridge_normalize_input(text).splitlines():
        line = raw_line.strip()
        if not line:
            continue
        reason = _fridge_reject_reason(line)
        if reason:
            rejected.append((_fridge_clean_name(line), reason))
    return rejected


def _fridge_is_product(name: str) -> bool:
    """Отсекает заголовки/пояснения, которые пользователь мог вставить вместе со списком."""
    n = name.lower().strip(" -—:•\t")
    if not n or len(n) < 2:
        return False
    if any(p in n for p in _FRIDGE_NOT_PRODUCT_PATTERNS):
        return False
    if n in _FRIDGE_NOT_PRODUCT_EXACT:
        return False
    return True


def _fridge_migrate(items: list) -> list:
    """Привести записи к категориям и стабильному порядку хранения. Отметки групп единого списка («group») —
    без изменений, по одной на группу."""
    result, groups = [], {}
    for it in items:
        if isinstance(it, dict) and it.get("group"):
            if it["group"] in GROUP_BY_ID:
                groups[it["group"]] = {**it, "cat": GROUP_BY_ID[it["group"]][0]}
            continue
        if isinstance(it, dict):
            names = _fridge_split_input(str(it.get("name", ""))) or [_fridge_clean_name(it.get("name", ""))]
            for name in names:
                if not _fridge_is_product(name):
                    continue
                detected = _fridge_detect_cat(name)
                stored = str(it.get("cat", "")).strip().lower()
                remapped = stored if stored in _CAT_VALID else _CAT_REMAP.get(stored)
                if it.get("cat_manual") and stored in _CAT_VALID:  # выбранная вручную новая категория
                    category = stored
                else:  # старая категория — по типу продукта, не вышло — ближайшая новая
                    category = detected or remapped or "крупы, макароны и хлеб"
                result.append({**it, "name": name, "cat": category})
        else:
            for s in _fridge_split_input(str(it)):
                if not _fridge_is_product(s):
                    continue
                result.append({"name": s, "cat": _fridge_cat(s), "on": True})
    dedup = {f"#{gid}": item for gid, item in groups.items()}
    for it in result:
        key = it["name"].casefold()
        if key in dedup:
            dedup[key]["on"] = bool(dedup[key].get("on", True) or it.get("on", True))
        else:
            dedup[key] = it
    order = {category: index for index, category in enumerate((*_CAT_ORDER, NOT_FOR_COOKING))}
    return sorted(
        dedup.values(),
        key=lambda item: (order[item["cat"]], item["name"].casefold()),
    )


def _fridge_available(items: list) -> list:
    """Мои продукты — отмеченные группы единого списка с примерами («Белая рыба (треска, судак)») для рецепта
    «Из моих продуктов»; записи прежних версий и то, из чего не готовят, не идут."""
    items = _fridge_migrate(items)
    if any(item.get("group") for item in items):
        return [group_label(gid) for gid in favorite_ids(items)]
    # Список ещё не перенесён в группы (экран «Мои продукты» не открывали): прежние отметки → их группы.
    marked = {match_group(item["name"]) for item in items if item.get("on", True)} - {None}
    return [group_label(gid) for gid in GROUP_BY_ID if gid in marked]
